//! The library lock: one line per definition and one per limit, generated from the catalogue and held to the committed
//! file `library.lock` at the crate root.
//!
//! The lock pins definitions, never implementations. A line hashes a definition's signature, its written semantics and
//! its known-answer cases, and records its parity and cost. A changed or removed line fails the test, and so does an
//! added one until the file is written again. `HENAD_WRITE_LIBRARY_LOCK=1` writes it. The test also prints which corpus
//! files use each kind, as information.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use henad_core::explore::fingerprint::fnv1a64;

use super::corpus;
use crate::GraphFile;
use crate::catalogue::{NodeDef, Parity, definitions};
use crate::limits;

/// Path of the lock, from the crate root.
const LOCK_PATH: &str = "library.lock";

/// Returns the hash of `text` as sixteen hexadecimal digits.
fn hash(text: &str) -> String {
    format!("{:016x}", fnv1a64(text.as_bytes()))
}

/// Returns the lock line of `def`.
fn lock_line(def: &NodeDef) -> String {
    let signature = format!(
        "{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}",
        def.type_var,
        def.config,
        def.inputs,
        def.outputs,
        def.config_ports,
        def.inner_outputs,
        def.is_region,
        def.contexts,
        def.domain,
        def.effects,
        def.backends,
    );
    let parity = match def.parity {
        Parity::Exact => "exact",
        Parity::Approx => "approx",
    };
    format!(
        "kind {} since={} signature={} semantics={} cases={} parity={parity} cost={:?}",
        def.id,
        def.since,
        hash(&signature),
        hash(def.semantics),
        hash(&format!("{:?}", def.cases)),
        def.cost,
    )
}

/// Returns the text of the lock.
fn lock_text() -> String {
    let mut text = String::from(
        "# Node library lock of henad-graph. Generated by the test `the_library_lock_matches_the_catalogue`.\n",
    );
    let mut lines: Vec<String> = definitions().map(lock_line).collect();
    lines.sort();
    for line in lines {
        text.push_str(&line);
        text.push('\n');
    }
    let limits: [(&str, u64); 27] = [
        ("MAX_FILE_BYTES", limits::MAX_FILE_BYTES as u64),
        ("MAX_NODES_PER_BODY", limits::MAX_NODES_PER_BODY as u64),
        ("MAX_NODES_IN_FILE", limits::MAX_NODES_IN_FILE as u64),
        ("MAX_NODES_INLINED", limits::MAX_NODES_INLINED as u64),
        ("MAX_PASSES", limits::MAX_PASSES as u64),
        ("MAX_FUNCTIONS", limits::MAX_FUNCTIONS as u64),
        ("MAX_CALL_DEPTH", limits::MAX_CALL_DEPTH as u64),
        ("MAX_LANES_PER_DOMAIN", limits::MAX_LANES_PER_DOMAIN as u64),
        ("MAX_FIELDS", limits::MAX_FIELDS as u64),
        ("MAX_LAYERS_PER_FIELD", limits::MAX_LAYERS_PER_FIELD as u64),
        ("MAX_COUNTERS", limits::MAX_COUNTERS as u64),
        ("MAX_CATEGORIES", limits::MAX_CATEGORIES as u64),
        ("MAX_VARIANTS", limits::MAX_VARIANTS as u64),
        ("MAX_PALETTES", limits::MAX_PALETTES as u64),
        ("MAX_PALETTE_COLORS", limits::MAX_PALETTE_COLORS as u64),
        ("MAX_PARAMS", limits::MAX_PARAMS as u64),
        ("MAX_STATS", limits::MAX_STATS as u64),
        ("MAX_ACTIONS", limits::MAX_ACTIONS as u64),
        ("MAX_ACCUMULATORS", limits::MAX_ACCUMULATORS as u64),
        ("MAX_TRANSITION_RULES", limits::MAX_TRANSITION_RULES as u64),
        ("MAX_PICK_VALUES", limits::MAX_PICK_VALUES as u64),
        ("MAX_POWI_EXPONENT", u64::from(limits::MAX_POWI_EXPONENT)),
        ("MAX_REPEAT_ITERATIONS", u64::from(limits::MAX_REPEAT_ITERATIONS)),
        ("MAX_REGION_DEPTH", limits::MAX_REGION_DEPTH as u64),
        ("MAX_FOLD_CANDIDATES", u64::from(limits::MAX_FOLD_CANDIDATES)),
        ("MAX_PASS_COST", u64::from(limits::MAX_PASS_COST)),
        ("MAX_GRID_SIDE", u64::from(limits::MAX_GRID_SIDE)),
    ];
    for (name, value) in limits {
        writeln!(text, "limit 1 {name}={value}").expect("a string takes every write");
    }
    for (name, value) in [
        ("MAX_ID_BYTES", limits::MAX_ID_BYTES as u64),
        ("MAX_LABEL_BYTES", limits::MAX_LABEL_BYTES as u64),
        ("MAX_DESCRIPTION_BYTES", limits::MAX_DESCRIPTION_BYTES as u64),
        ("MAX_EXPRESSION_BYTES", limits::MAX_EXPRESSION_BYTES as u64),
        ("MAX_AGENTS", u64::from(limits::MAX_AGENTS)),
    ] {
        writeln!(text, "limit 1 {name}={value}").expect("a string takes every write");
    }
    text
}

/// Returns the corpus files that use each kind, by kind.
fn used_by() -> BTreeMap<String, BTreeSet<String>> {
    let mut used: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for (name, text) in corpus::all() {
        let Ok(file) = GraphFile::parse(&text) else { continue };
        let document = file.document();
        let bodies = document
            .passes
            .iter()
            .map(|pass| &pass.body)
            .chain(document.functions.iter().map(|function| &function.body));
        for body in bodies {
            for node in &body.nodes {
                used.entry(node.op.clone())
                    .or_default()
                    .insert(name.trim_end_matches(".toml").to_owned());
            }
        }
    }
    used
}

#[test]
#[expect(
    clippy::print_stdout,
    reason = "the Used by table is information for a reader of the test output"
)]
fn the_library_lock_matches_the_catalogue() {
    let without_cases: Vec<&str> = definitions()
        .filter(|def| def.cases.is_empty())
        .map(|def| def.id)
        .collect();
    assert!(
        without_cases.is_empty(),
        "kinds without known-answer cases: {without_cases:?}"
    );

    let used = used_by();
    println!("Used by, from the corpus:");
    for def in definitions() {
        let users = used.get(def.id).map_or_else(
            || "none".to_owned(),
            |users| users.iter().cloned().collect::<Vec<_>>().join(", "),
        );
        println!("| `{}` | {users} |", def.id);
    }

    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(LOCK_PATH);
    let generated = lock_text();
    if std::env::var_os("HENAD_WRITE_LIBRARY_LOCK").is_some() {
        std::fs::write(&path, &generated).expect("the lock is written");
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    let committed_lines: BTreeSet<&str> = committed.lines().collect();
    let generated_lines: BTreeSet<&str> = generated.lines().collect();
    let gone: Vec<&&str> = committed_lines.difference(&generated_lines).collect();
    let added: Vec<&&str> = generated_lines.difference(&committed_lines).collect();
    assert!(
        gone.is_empty(),
        "lines of the lock changed or went, which changes a definition:\n{gone:#?}\nnew lines:\n{added:#?}"
    );
    assert!(
        added.is_empty(),
        "the catalogue adds lines the lock lacks. Write it with HENAD_WRITE_LIBRARY_LOCK=1:\n{added:#?}"
    );
}
